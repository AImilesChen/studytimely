"""Generate the supported-city transition table from pinned PSF tzdata data only.

Uses Python's standard-library TZif reader; does not install or execute the wheel.
Run from app/: python scripts/update-time-zones.py
"""
import datetime as dt
import hashlib
import io
import json
from pathlib import Path
import re
import urllib.request
import zipfile
from zoneinfo import ZoneInfo

ROOT = Path(__file__).resolve().parents[1]
URL = 'https://files.pythonhosted.org/packages/0a/66/9a06c2227fedfd4919f0eaaa8b94377d9730882a7e4f95823c9a331ab5e1/tzdata-2026.6-py2.py3-none-any.whl'
SHA = '0a10eec6e13ef16b627fabed9a5f2ba61a62b1c67f327305f4e7e412a70b4aec'
cache = ROOT / '.wrangler' / 'tzdata-2026.6.whl'
cache.parent.mkdir(exist_ok=True)
payload = cache.read_bytes() if cache.exists() else urllib.request.urlopen(URL, timeout=60).read()
assert hashlib.sha256(payload).hexdigest() == SHA, 'Pinned tzdata archive hash mismatch'
cache.write_bytes(payload)
archive = zipfile.ZipFile(io.BytesIO(payload))
assert archive.read('tzdata/zoneinfo/tzdata.zi').startswith(b'# version 2026f\n')
source = (ROOT / 'src/lib/world-clock.mjs').read_text(encoding='utf-8')
zones = sorted(set(re.findall(r"\['[a-z-]+','[^']+','[^']+','([A-Za-z_]+/[A-Za-z_]+)'", source)))
assert len(zones) == 31, 'Expected 32 cities sharing 31 IANA zones'
start = int(dt.datetime(1970, 1, 1, tzinfo=dt.timezone.utc).timestamp())
end = int(dt.datetime(2101, 1, 1, tzinfo=dt.timezone.utc).timestamp())
result = {'version': '2026f', 'start': start, 'end': end,
          'source': {'package': 'tzdata 2026.6', 'url': URL, 'sha256': SHA}, 'zones': {}}
for zone in zones:
    tz = ZoneInfo.from_file(io.BytesIO(archive.read('tzdata/zoneinfo/' + zone)), key=zone)
    def state(stamp):
        local = dt.datetime.fromtimestamp(stamp, dt.timezone.utc).astimezone(tz)
        return [int(local.utcoffset().total_seconds() / 60), bool(local.dst()), local.tzname()]
    previous, last_probe = state(start), start
    rows = [[start, *previous]]
    for probe in range(start + 21600, end, 21600):
        current = state(probe)
        if current != previous:
            low, high = last_probe, probe
            while high - low > 1:
                mid = (low + high) // 2
                if state(mid) == previous:
                    low = mid
                else:
                    high = mid
            rows.append([high, *state(high)])
        previous, last_probe = current, probe
    result['zones'][zone] = rows
output = ROOT / 'src/lib/time-zone-data.mjs'
output.write_text('// Generated by scripts/update-time-zones.py from pinned IANA data.\n'
                  'export const TIME_ZONE_DATA=' + json.dumps(result, separators=(',', ':'), ensure_ascii=False) + ';\n', encoding='utf-8')
license_names = [n for n in archive.namelist() if n.endswith('/licenses/LICENSE_APACHE')]
assert len(license_names) == 1
(ROOT / 'public/time-zone-data-license.txt').write_bytes(archive.read(license_names[0]))
print(json.dumps({'version': result['version'], 'zones': len(zones), 'bytes': output.stat().st_size,
                  'transitions': sum(len(v) for v in result['zones'].values())}))
