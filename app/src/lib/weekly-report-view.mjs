import {duration} from './study-analysis.mjs';

export function weeklyReportOrigin(ai){
 // The isolated development fixture deliberately puts this marker in its result.
 // Keep that fixture visibly distinct in the page AND all downloaded formats.
 const example=(ai.content.summary||ai.content.overview?.summary||'').startsWith('Synthetic local test report:');
 return {example,badge:example?'Example · not AI-generated':'AI-generated with DeepSeek',description:example?'Illustrative local report. No live AI generation was used.':'Generated by DeepSeek from your saved study records.',attribution:example?'Local example · not a live AI result':'AI-generated with DeepSeek'};
}

// Both the screen and the standalone download read the saved snapshot only.
export function weeklyReportFigures(f){
 const start=new Date(f.start+'T12:00:00Z'),end=new Date(f.end+'T12:00:00Z'),date=new Intl.DateTimeFormat('en-GB',{day:'numeric',month:'short',year:'numeric',timeZone:'UTC'});
 const rangeLabel=start.getUTCFullYear()===end.getUTCFullYear()&&start.getUTCMonth()===end.getUTCMonth()?`${start.getUTCDate()}–${date.format(end)}`:`${date.format(start)} – ${date.format(end)}`;
 const max=Math.max(1,...f.days.map(d=>d.seconds));
 const days=f.days.map(d=>({...d,label:new Intl.DateTimeFormat('en-GB',{weekday:'short',timeZone:'UTC'}).format(new Date(d.date+'T12:00:00Z')),value:duration(d.seconds),height:d.seconds/max*100}));
 const sorted=[...f.subjects].sort((a,b)=>b.seconds-a.seconds),subjects=sorted.slice(0,3);
 if(sorted.length>3)subjects.push({id:'other',name:'Other subjects',seconds:sorted.slice(3).reduce((n,s)=>n+s.seconds,0)});
 const delta=f.previous?.count?f.seconds-f.previous.seconds:null;
 return {rangeLabel,days,subjects:subjects.map(s=>({...s,value:duration(s.seconds),share:f.seconds?s.seconds/f.seconds*100:0})),comparison:delta===null?'No previous saved sessions to compare':delta===0?'Same saved time as the previous period':`${duration(Math.abs(delta))} ${delta>0?'more':'less'} than the previous period`};
}
export function shortWeeklyEvidence(f,key){
 if(key==='total')return `${duration(f.seconds)} · ${f.count} sessions`;
 if(key==='days')return `${f.activeDays} study days`;
 if(key==='tasks')return `${f.completed} dated task completions · ${f.planned} planned`;
 if(key==='comparison')return weeklyReportFigures(f).comparison;
 if(key==='goals')return `${f.goals?.reached||0}/${f.goals?.eligible||0} known goal days reached`;
 if(key==='estimates')return `${f.estimates?.count||0} completed tasks with estimates`;
 const subject=f.subjects.find(s=>s.id===key);return subject?`${subject.name}: ${duration(subject.seconds)}`:'';
}
